#!/usr/bin/env python3
"""Generate bun-ant/fused-data.js from Bun's stringWidthTables.h.

Usage: gen-fused-data.py <stringWidthTables.h> <out.js>

stringWidthTables.h (oven-sh/bun, src/jsc/bindings/, MIT) is a 3-stage
lookup giving one packed byte per code point: grapheme break class (bits
0-4), width class (bits 5-6) and the emoji bit (bit 7). The output is the
same table run-length encoded: FUSED_DELTAS[i] is the distance from the
previous run start, FUSED_VALUES[i] the packed byte for that run.

Fetch the header for the Bun version in use, e.g.
  https://raw.githubusercontent.com/oven-sh/bun/bun-v1.4.4/src/jsc/bindings/stringWidthTables.h
"""
import json, re, sys

src, dst = sys.argv[1], sys.argv[2]
h = open(src).read()


def table(name):
    m = re.search(r"k" + name + r"\[(\d+)\]\s*=\s*\{(.*?)\};", h, re.S)
    if not m:
        sys.exit("table %s not found in %s" % (name, src))
    vals = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", m.group(2))]
    if len(vals) != int(m.group(1)):
        sys.exit("table %s: expected %s entries, got %d" % (name, m.group(1), len(vals)))
    return vals


s1, s2, s3 = (table("GraphemeBreakStage" + n) for n in "123")
packed = [s3[s2[s1[cp >> 8] + (cp & 0xFF)]] for cp in range(0x110000)]
starts, values = [0], [packed[0]]
for cp in range(1, 0x110000):
    if packed[cp] != packed[cp - 1]:
        starts.append(cp)
        values.append(packed[cp])
deltas = [starts[0]] + [starts[i] - starts[i - 1] for i in range(1, len(starts))]

ver = re.search(r"Unicode\s*(?://\s*)?(\d+\.\d+\.\d+)", h)
with open(dst, "w") as f:
    f.write("// Generated by tools/gen-fused-data.py from Bun's stringWidthTables.h\n")
    f.write("// (Unicode %s). Do not edit; regenerate instead.\n" % (ver.group(1) if ver else "?"))
    f.write("export const FUSED_DELTAS = " + json.dumps(deltas, separators=(",", ":")) + ";\n")
    f.write("export const FUSED_VALUES = " + json.dumps(values, separators=(",", ":")) + ";\n")
print("%d runs" % len(starts))
